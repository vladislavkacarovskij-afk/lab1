import sympy as sp # Підключаємо бібліотеку символьної математики sympy

def run(): # Оголошуємо функцію запуску модуля
    x = sp.Symbol('x') # Оголошуємо алгебраїчну змінну x
    factored = sp.factor(x**2 - 9) # Розкладаємо вираз x^2 - 9 на множники
    print(f"  - sympy: Множники = {factored}") # Виводимо результат розкладання