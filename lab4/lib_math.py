import math # Підключаємо вбудовану математичну бібліотеку

def run(): # Оголошуємо функцію запуску модуля
    val = 90 # Задаємо змінну зі значенням кута в градусах
    result = math.sin(math.radians(val)) # Переводимо в радіани та рахуємо синус
    print(f"  - math: Синус {val}° = {result}") # Виводимо результат у консоль